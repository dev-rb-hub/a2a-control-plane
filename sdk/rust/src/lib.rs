//! Rust SDK for the a2a-control-plane open standard.
//!
//! This crate is the I/O-free core: wire types generated from `schemas/v1`, and pure functions and
//! state for identities, subjects and their permissions, the Worker state machine, adaptive
//! heartbeats, capability maps, the byte-exact signed and hashed payloads, voucher signatures and
//! reconnect backoff. Time is always an argument. There is no async runtime, no thread and no
//! network code here; transports belong at the edge (`rfcs/0005-async-model.md`).
//!
//! Behaviour is checked against the language-neutral vectors in `conformance/vectors`, which are
//! generated from the Python reference implementation.

pub mod backoff;
pub mod capabilities;
pub mod heartbeat;
pub mod identity;
pub mod payloads;
pub mod state;
pub mod subjects;
pub mod tokens;
pub mod voucher;

/// Wire types of package `a2a.controlplane.v1`, generated by `prost` from `schemas/v1`.
pub mod proto {
    #![allow(clippy::all, missing_docs)]
    include!(concat!(env!("OUT_DIR"), "/a2a.controlplane.v1.rs"));
}

/// The `a2a-type` header that names the protobuf message carried in a bus message (spec 03, 4).
pub const TYPE_HEADER: &str = "a2a-type";
/// Default maximum message size, 64 KiB (spec 05, section 5).
pub const MAX_MESSAGE_BYTES: usize = 64 * 1024;
